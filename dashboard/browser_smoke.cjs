const { chromium } = require(process.env.TEMP + "/quantumtn-browser/node_modules/playwright-core");
const assert = require("node:assert/strict");
(async()=>{
 const browser=await chromium.launch({channel:"msedge",headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1450,height:1000}});
  const errors=[];
  page.on("pageerror",e=>errors.push(e.message));
  await page.goto("http://127.0.0.1:8765/");
  await page.waitForSelector("#chart");
  assert.match(await page.locator("#detail").innerText(),/5\.08%/);
  await page.locator("#flowDiagram button").nth(5).click();
  assert.match(await page.locator("#flowName").innerText(),/Execute repeated shots/);
  const geometry=await page.locator("#flowScene").innerHTML();
  await page.locator("#flowAngle").fill("28");
  assert.notEqual(await page.locator("#flowScene").innerHTML(),geometry);
  await page.locator("#flowScene [data-stage='7']").click();
  assert.match(await page.locator("#flowName").innerText(),/Count logical failures/);
  for(const key of ["pipeline","twirling"])await page.locator(`[data-key="${key}"][data-value="All"]`).click();
  assert.doesNotMatch(await page.locator("#visualization .key").innerText(),/qiskit · unspecified/i);
  await page.locator('[data-key="basis"][data-value="X"]').click();
  assert.match(await page.locator("#detail").innerText(),/50 failures/);
  await page.locator('[data-key="basis"][data-value="Z"]').click();
  await page.locator('[data-key="pipeline"][data-value="qrisp"]').click();
  await page.locator('[data-key="twirling"][data-value="true"]').click();
  await page.locator("#topologyGraphic svg").waitFor();
  const raw=page.waitForEvent("download");
  await page.getByRole("link",{name:"Download raw source"}).click();
  assert.match((await raw).suggestedFilename(),/raw\.npz$/);
  await page.locator("#shotButton").click();
  await page.locator("#shotDetails svg").waitFor();
  await page.getByRole("button",{name:"Distance 5",exact:true}).click();
  assert.match(await page.locator("#detail").innerText(),/36\.30%/);
  const picker=page.getByLabel("Measurement at selected round");
  await picker.selectOption({index:0});
  assert.match(await page.locator("#detail").innerText(),/36\.10%/);
  await page.getByRole("button",{name:"Qrisp",exact:true}).click();
  assert.match(await page.locator("#detail").innerText(),/No IQM hardware measurement/);
  await page.getByRole("button",{name:"Select pilot settings",exact:true}).click();
  assert.match(await page.locator("#detail").innerText(),/36[13] failures/);
  await page.getByRole("button",{name:"3D surface code",exact:true}).click();
  assert.equal(await page.locator("#visualization [data-qubit]").count(),49);
  await page.getByRole("button",{name:"Advance error demo"}).click();
  await page.getByRole("button",{name:"Advance error demo"}).click();
  assert.match(await page.locator("#visualization").innerText(),/Anticommuting stabilizers/);
  await page.getByRole("button",{name:"Play",exact:true}).click();
  await page.getByRole("button",{name:"Pause",exact:true}).click();
  assert.equal(await page.locator("#deck,#presentation").count(),0);
  await page.locator("#flowDiagram button").nth(2).click();
  assert.match(await page.locator("#flowName").innerText(),/readout bias/);
  await page.locator("#flowTwirl").click();
  await page.locator("#flowScene [data-step='3']").click();
  assert.match(await page.locator("#flowScene").textContent(),/5.08%/);
  const chip=await page.locator("#transmon").innerHTML();
  await page.locator("#chipRotation").fill("24");
  assert.notEqual(await page.locator("#transmon").innerHTML(),chip);
  assert.match(await page.locator("#distances").textContent(),/36.30%/);
  assert.match(await page.locator("#recommendation").textContent(),/5.08%/);
  await page.locator("#noise-distance").selectOption("5");
  await page.locator("#noise-shots").fill("64");
  await page.locator("#noise-basis").selectOption("X");
  await page.getByRole("button",{name:"Run quantum noise simulation",exact:true}).click();
  await page.waitForFunction(()=>document.querySelector("#simStatus").textContent.includes("/ 64 failures"));
  const download=page.waitForEvent("download");
  await page.getByRole("button",{name:"Download CSV",exact:true}).click();
  assert.equal((await download).suggestedFilename(),"experiments.csv");
  assert.deepEqual(errors,[]);
  console.log("Edge passed archive, shot view, missing d=5 selection, 49-node viewer, simulator, device and workflow models and CSV.");
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});


